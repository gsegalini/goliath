"""Render a tidy table DataFrame to booktabs LaTeX and to CSV.

The CSV is the traceable artifact; the .tex is a rendering of it. Both are written from the same
frame so they can never disagree.
"""
from __future__ import annotations

import os
import re

import pandas as pd

_LATEX_ESCAPES = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_"}


def _cell(v) -> str:
    """Escape a cell for LaTeX.

    Handles the markers our table functions emit as plain text:
      "a +- b" -> $a \\pm b$        (mean/std)
      "~1234"  -> $\\approx$1234    (a bare ~ is a non-breaking SPACE in LaTeX, which would
                                    silently drop the approximation sign)
      "inf"    -> $\\infty$
      "a-b"    -> a--b              (en dash for numeric ranges, not a hyphen)
    """
    s = "" if v is None or (isinstance(v, float) and pd.isna(v)) else str(v)
    if s == "-":
        return "--"
    if "+-" in s:
        left, right = (p.strip() for p in s.split("+-", 1))
        return f"${_cell(left)} \\pm {_cell(right)}$".replace("$$", "")
    for k, r in _LATEX_ESCAPES.items():
        s = s.replace(k, r)
    s = re.sub(r"\binf\b", r"$\\infty$", s)
    s = re.sub(r"~\s*([\d.]+(?:e[+-]?\d+)?)", r"$\\approx$\1", s)
    # numeric range: digit-hyphen-digit becomes an en dash
    s = re.sub(r"(?<=\d)-(?=\d)", "--", s)
    # a bare +N.Npp reads better as math
    s = re.sub(r"^([+-][\d.]+)pp$", r"$\1$\\,pp", s)
    return s


def _header(name: str) -> str:
    s = str(name)
    for k, r in _LATEX_ESCAPES.items():
        s = s.replace(k, r)
    s = s.replace(">=", r"$\geq$").replace("<=", r"$\leq$")
    return rf"\textbf{{{s}}}"


def write_latex(df: pd.DataFrame, spec, path: str) -> None:
    """Write a standalone booktabs table, ready to \\input."""
    numeric = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]
    align = "".join("r" if c in numeric or i > 0 else "l" for i, c in enumerate(df.columns))
    lines = [
        "% Generated by analysis/build.py -- do not edit by hand.",
        f"% Regenerate: uv run analysis/build.py --tables",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        rf"\begin{{tabular}}{{{align}}}",
        r"\toprule",
        " & ".join(_header(c) for c in df.columns) + r" \\",
        r"\midrule",
    ]
    for _, row in df.iterrows():
        lines.append(" & ".join(_cell(v) for v in row) + r" \\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        rf"\caption{{{spec.caption}}}",
        rf"\label{{{spec.label}}}",
        r"\end{table}",
        "",
    ]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines))


def write_csv(df: pd.DataFrame, path: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    df.to_csv(path, index=False)
